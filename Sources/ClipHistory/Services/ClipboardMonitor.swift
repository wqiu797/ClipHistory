import AppKit
import CryptoKit
import Foundation

final class ClipboardMonitor: @unchecked Sendable {
    static let shared = ClipboardMonitor()

    /// Pasteboard types that must never be captured: password managers and other sensitive sources
    /// flag their content with these.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Capture runs here so decoding, hashing and disk/DB writes never block the main thread.
    private let captureQueue = DispatchQueue(
        label: "com.cliphistory.clipboard.capture",
        qos: .utility
    )

    private var timer: Timer?
    private var lastChangeCount: Int = NSPasteboard.general.changeCount
    private var ownWriteChangeCount: Int = -1
    private let dao = ClipboardItemDAO()
    private let imageStore = ImageStore.shared

    /// Always invoked on the main thread.
    var onNewItem: ((ClipboardItem) -> Void)?

    private init() {}

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Call this *after* writing to the pasteboard, never before. Recording the change count before
    /// the write makes the monitor capture its own write on the next poll.
    func markOwnWrite() {
        ownWriteChangeCount = NSPasteboard.general.changeCount
    }

    // MARK: - Polling

    private func poll() {
        let pasteboard = NSPasteboard.general
        let currentCount = pasteboard.changeCount

        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        // Skip changes we caused ourselves.
        if currentCount == ownWriteChangeCount {
            ownWriteChangeCount = -1
            return
        }

        guard !containsSensitiveType(pasteboard) else {
            Log.clipboard.debug("Skipped a concealed/transient pasteboard item")
            return
        }

        let sourceApp = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        {
            captureQueue.async { [weak self] in
                self?.captureText(text, sourceApp: sourceApp)
            }
        } else if let data = imageData(from: pasteboard) {
            captureQueue.async { [weak self] in
                self?.captureImage(data, sourceApp: sourceApp)
            }
        }
    }

    private func containsSensitiveType(_ pasteboard: NSPasteboard) -> Bool {
        guard let types = pasteboard.types else { return false }
        return types.contains { Self.ignoredTypes.contains($0) }
    }

    private func imageData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) {
            return png
        }
        if let tiff = pasteboard.data(forType: .tiff) {
            return tiff
        }
        if let image = pasteboard.readObjects(forClasses: [NSImage.self], options: nil)?.first as? NSImage {
            return image.tiffRepresentation
        }
        return nil
    }

    // MARK: - Capture (background queue)

    private func captureText(_ text: String, sourceApp: String?) {
        let hash = Self.sha256Hex(Data(text.utf8))

        do {
            if let existing = try dao.touch(hash: hash) {
                notify(existing)
                return
            }

            let item = ClipboardItem(
                contentType: .text,
                textContent: text,
                sourceAppBundleId: sourceApp,
                createdAt: Date(),
                contentHash: hash
            )
            notify(try dao.insert(item))
        } catch {
            Log.clipboard.error("Failed to save text clipboard: \(String(describing: error), privacy: .public)")
        }
    }

    private func captureImage(_ data: Data, sourceApp: String?) {
        guard let encoded = imageStore.encode(data) else { return }

        do {
            // Deduplicate *before* writing files so repeated copies never leak orphans.
            if let existing = try dao.touch(hash: encoded.contentHash) {
                notify(existing)
                return
            }

            guard let files = imageStore.write(encoded) else { return }

            let item = ClipboardItem(
                contentType: .image,
                imageFileName: files.imageName,
                thumbnailFileName: files.thumbnailName,
                sourceAppBundleId: sourceApp,
                createdAt: Date(),
                contentHash: encoded.contentHash
            )

            do {
                notify(try dao.insert(item))
            } catch {
                // Never leave files behind if the row could not be inserted.
                imageStore.deleteImages(imageName: files.imageName, thumbName: files.thumbnailName)
                throw error
            }
        } catch {
            Log.clipboard.error("Failed to save image clipboard: \(String(describing: error), privacy: .public)")
        }
    }

    private func notify(_ item: ClipboardItem) {
        DispatchQueue.main.async { [weak self] in
            self?.onNewItem?(item)
        }
    }

    private static func sha256Hex(_ data: Data) -> String {
        SHA256.hash(data: data)
            .map { String(format: "%02x", $0) }
            .joined()
    }
}
